/**
 * Връща статус на достойнство ('domicile' | 'exaltation' | 'detriment' | 'fall' | null)
 * за дадена планета в даден знак.
 */
function getPlanetDignity(planetId, signId) {
  const d = PLANET_DIGNITIES[planetId];
  if (!d) return null;
  if (d.domicile.includes(signId)) return "domicile";
  if (d.exaltation.includes(signId)) return "exaltation";
  if (d.detriment.includes(signId)) return "detriment";
  if (d.fall.includes(signId)) return "fall";
  return null;
}

